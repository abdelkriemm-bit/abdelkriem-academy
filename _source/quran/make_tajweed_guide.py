errs = []
codes = {c["code"] for c in C}
def chk(e, where):
    t = qdata.ayah_text(e["surah"], e["ayah"])
    if not qrender.highlight(t, e["word"])[1]: errs.append(("highlight", where, e))
    # stricter: every word of e["word"] appears verbatim in the ayah
    for w in e["word"].split():
        if w not in t.split(): errs.append(("verbatim", where, w, e["surah"], e["ayah"]))
def _sk(x): return qdata.skel(x.replace("ٮ", "ى")).replace("ـ", "")
def colour_hit(e, code):
    """strict: a span of `code` must start or end inside the example's own word(s), not only in the next word"""
    s, a = e["surah"], e["ayah"]
    pl, sp = qdata.parse_tajweed(qdata._T[s - 1]["ayahs"][a - 1]["text"])
    tw = [_sk(x) for x in pl.split(" ")]
    nz = [i for i, x in enumerate(tw) if x]
    def widx(pos): return sum(1 for x in tw[:len(pl[:pos].split(" ")) - 1] if x)
    seq = [tw[i] for i in nz]
    tgt = [_sk(x) for x in e["word"].split() if _sk(x)]
    for i in range(len(seq)):
        if seq[i:i + len(tgt)] == tgt:
            lo, hi = i, i + len(tgt) - 1
            for c, st, en in sp:
                if c == code and (lo <= widx(st) <= hi or lo <= widx(max(st, en - 1)) <= hi): return True
    return False
for g in G:
    for r in g["rules"]:
        assert r["code"] is None or r["code"] in codes, r
        assert 1 <= len(r["examples"]) <= 3, r["name"]
        for e in r["examples"]:
            chk(e, r["name"])
            if r["code"] and not colour_hit(e, r["code"]): errs.append(("colour", r["name"], r["code"], e))
for s in S:
    for e in s["examples"]: chk(e, s["name"])
