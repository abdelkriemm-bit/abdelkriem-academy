def E(s, a, w):
    """copy the exact word(s) from the verified Uthmani text (matched by skeleton)"""
    tw = qdata.ayah_text(s, a).split(" ")
    target = [qdata.skel(x) for x in w.split() if qdata.skel(x)]
    for i in range(len(tw)):
        j, k, seq = i, 0, []
        while j < len(tw) and k < len(target):
            if not qdata.skel(tw[j]):
                if seq: seq.append(j)
                j += 1; continue
            if qdata.skel(tw[j]) != target[k]: break
            seq.append(j); j += 1; k += 1
        if k == len(target) and seq:
            return {"surah": s, "ayah": a, "word": " ".join(tw[seq[0]:seq[-1] + 1])}
    raise SystemExit(f"not found: {s}:{a} {w}")

def R(name, code, spot, do, count, ex):
    return {"name": name, "code": code, "spot": spot, "do": do, "count": count, "examples": ex}

