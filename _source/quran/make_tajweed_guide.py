PH = re.compile(r"⟦(\d+):(\d+):([^⟧]+)⟧")
def fill(x):
    if isinstance(x, str): return PH.sub(lambda m: E(int(m.group(1)), int(m.group(2)), m.group(3))["word"], x)
    if isinstance(x, list): return [fill(y) for y in x]
    if isinstance(x, dict): return {k: (v if k == "examples" else fill(v)) for k, v in x.items()}
    return x
